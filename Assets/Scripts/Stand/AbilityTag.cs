using System;

/// <summary>
/// Теги способностей — язык гейтинга метроидвании.
///
/// Мир спрашивает «есть ли у стенда тег X», а не «это стенд Y».
/// Одна способность может нести несколько тегов; стенд обладает тегом,
/// если им обладает любая его способность (StandController.HasAbilityTag).
///
/// Значения совпадают со скелетом docs/StandSystem/StandSystem.cs, чтобы
/// дизайн-док и код не разъезжались. Расширять — только добавляя новые
/// биты в конец: старые ассеты хранят маску по значению.
/// </summary>
[Flags]
public enum AbilityTag
{
    None        = 0,
    HeavyImpact = 1 << 0,   // разбить стену / тяжёлый пролом
    Grapple     = 1 << 1,   // дотянуться через пропасть (Hermit Purple, Stone Free)
    Phase       = 1 << 2,   // пролезть / распутаться / фазировать
    TimeControl = 1 << 3,   // остановка/замедление времени
    Heal        = 1 << 4,   // восстановление (Crazy Diamond)
    Trap        = 1 << 5,   // ставить зоны/ловушки (Echoes Act 2)
    Gather      = 1 << 6,   // собирать/переносить предметы (Harvest)
}
